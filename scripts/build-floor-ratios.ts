/**
 * Measure value-to-opening-bid ratios per state and write the floor table.
 *
 *   npx tsx scripts/build-floor-ratios.ts
 *
 * Writes `lib/deal/floor-ratios.ts`. Generated rather than hand-authored
 * because the numbers are an observation about inventory, not a statutory
 * fact — and generated into *code* rather than read at runtime because
 * `computeMaxBid` runs in the browser inside `DealCalculator` and has no
 * database.
 *
 * Only states with `MIN_SAMPLE` observed pairs get an entry. A state with
 * eleven parcels does not have a ratio, it has eleven parcels, and inventing
 * one for it would put a number under a parcel nobody can check.
 */
import "../lib/env";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { sql } from "drizzle-orm";
import { db } from "../lib/db";
import { statuteFor } from "../lib/deal/statute";

/** Below this, a state has anecdotes rather than a distribution. */
const MIN_SAMPLE = 100;

/**
 * Percentile of a sorted array, linear interpolation.
 *
 * Computed here rather than in SQL because the values have to be converted to
 * a common scale first, and that conversion needs `statuteFor`.
 */
function percentile(sorted: number[], p: number): number {
  if (sorted.length === 0) return NaN;
  const i = (sorted.length - 1) * p;
  const lo = Math.floor(i);
  const hi = Math.ceil(i);
  const v = lo === hi ? sorted[lo] : sorted[lo] + (sorted[hi] - sorted[lo]) * (i - lo);
  return Math.round(v * 100) / 100;
}

async function main() {
  const raw = (await db.execute(
    sql.raw(`
      SELECT c.state,
             l.opening_bid::float8 AS bid,
             v.market_value::float8 AS mkt,
             l.assessed_value::float8 AS assd
      FROM lots l
      JOIN auctions a ON a.id = l.auction_id
      JOIN counties c ON c.fips = a.county_fips
      LEFT JOIN LATERAL (
        SELECT market_value FROM lot_valuations lv
        WHERE lv.lot_id = l.id AND lv.market_value IS NOT NULL
        ORDER BY fetched_at DESC LIMIT 1
      ) v ON true
      WHERE a.listing_kind = 'sale_list' AND a.sale_date_confirmed
        AND l.opening_bid > 0
        AND COALESCE(v.market_value, l.assessed_value) > 0`),
  )) as unknown as { state: string; bid: number; mkt: number | null; assd: number | null }[];

  /*
   * Everything is converted to a market-equivalent value before the ratio is
   * taken. The first version of this coalesced market value over assessed value
   * and divided by the opening bid, which silently mixed two scales in one
   * table: Arkansas's 889 pairs were all market values, while Michigan's 2,189
   * and Texas's 669 were all assessed. Texas assesses at 1.0 so it came out
   * right by luck; Michigan's SEV is half of true cash value, so its ratio was
   * half what it should have been and every Michigan floor understated the
   * property twofold.
   *
   * An assessed value with no state ratio to convert it is dropped rather than
   * used raw. A ratio table that cannot say what scale it is on is worse than a
   * missing one, because it looks usable.
   */
  const byState = new Map<string, number[]>();
  let usedMarket = 0;
  let usedAssessed = 0;
  let droppedNoRatio = 0;

  for (const r of raw) {
    let marketEquivalent: number | null = null;
    if (r.mkt !== null && r.mkt > 0) {
      marketEquivalent = r.mkt;
      usedMarket++;
    } else if (r.assd !== null && r.assd > 0) {
      const ratio = statuteFor(r.state)?.assessmentRatio;
      if (!ratio) {
        droppedNoRatio++;
        continue;
      }
      marketEquivalent = r.assd / ratio;
      usedAssessed++;
    }
    if (marketEquivalent === null) continue;
    const list = byState.get(r.state) ?? [];
    list.push(marketEquivalent / r.bid);
    byState.set(r.state, list);
  }

  console.log(
    `${usedMarket} pair(s) from market value, ${usedAssessed} converted from assessed, ` +
      `${droppedNoRatio} dropped for having neither a market value nor a state ratio`,
  );

  const rows = [...byState.entries()]
    .filter(([, v]) => v.length >= MIN_SAMPLE)
    .map(([state, values]) => {
      const sorted = [...values].sort((a, b) => a - b);
      return {
        state,
        n: sorted.length,
        p25: percentile(sorted, 0.25),
        median: percentile(sorted, 0.5),
        p75: percentile(sorted, 0.75),
      };
    })
    .sort((a, b) => a.state.localeCompare(b.state));

  const today = new Date().toISOString().slice(0, 10);
  const body = rows
    .map(
      (r) =>
        `  ${r.state}: { n: ${r.n}, p25: ${r.p25}, median: ${r.median}, p75: ${r.p75} },`,
    )
    .join("\n");

  const file = `/**
 * Observed value-to-opening-bid ratios, per state.
 *
 * GENERATED by scripts/build-floor-ratios.ts on ${today}. Do not hand-edit —
 * re-run it when inventory moves materially.
 *
 * Measured over parcels where an opening bid and a valuation are both known.
 * Every value is converted to a market-equivalent figure first — a provider
 * market estimate is used as-is, an assessed value is divided by the state's
 * assessment ratio, and an assessed value in a state with no known ratio is
 * dropped rather than mixed in on a different scale. Only states with at least
 * ${MIN_SAMPLE} usable pairs appear; the rest have no entry and get no floor,
 * which is the correct answer rather than a missing one.
 *
 * The spread is the point, not the median. Nationally the ratio runs 0.76 at
 * the 10th percentile to 24.20 at the 90th — a 32x range that makes any single
 * national multiple meaningless, and the state medians differ from each other
 * by 6x. That a tenth of parcels come in *below* 1.0 is the number that
 * matters most: those are worth less than their opening bid, so a floor is a
 * starting point for research and never a reason to bid.
 */
export interface FloorRatio {
  /** Observed pairs behind this row. */
  n: number;
  p25: number;
  median: number;
  p75: number;
}

export const FLOOR_RATIOS: Record<string, FloorRatio> = {
${body}
};

/** When the table was measured, for display next to any figure derived from it. */
export const FLOOR_RATIOS_AS_OF = "${today}";
`;

  const out = join(process.cwd(), "lib", "deal", "floor-ratios.ts");
  await writeFile(out, file);
  console.log(`${rows.length} state(s) with >= ${MIN_SAMPLE} pairs`);
  console.table(rows);
  console.log(`wrote ${out}`);
  process.exit(0);
}

main();
